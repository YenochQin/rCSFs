"""Collect notices from cached, locked Cargo dependencies without network access."""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
from pathlib import Path


def collect(root: Path) -> str:
    result = subprocess.run(
        ["cargo", "metadata", "--locked", "--offline", "--format-version", "1"],
        cwd=root,
        check=True,
        capture_output=True,
        text=True,
    )
    packages = json.loads(result.stdout)["packages"]
    fingerprint = hashlib.sha256((root / "Cargo.lock").read_bytes()).hexdigest()
    index = [
        "Rust dependency notices",
        "=======================",
        "",
        f"Cargo.lock SHA-256: {fingerprint}",
        "",
        "Generated by scripts/collect_licenses.py from the locked crate sources.",
        "Includes all resolved targets and build dependencies, a superset of",
        "the crates linked into any single platform's wheel. Each dependency",
        "retains its own license; the rcsfs MIT license does not replace it.",
        "Identical notice text is included once and referenced by its SHA-256.",
        "",
    ]
    notices: dict[str, str] = {}
    for package in sorted(packages, key=lambda item: (item["name"], item["version"])):
        if package["source"] is None:
            continue
        name = f"{package['name']}-{package['version']}"
        source = Path(package["manifest_path"]).parent
        override = root / "licenses" / "upstream" / f"{name}.txt"
        files = [
            path
            for path in sorted(source.rglob("*"))
            if path.is_file()
            and path.name.lower().startswith(
                ("license", "licence", "copying", "notice", "copyright", "authors")
            )
            and path.suffix.lower() not in {".rs", ".c", ".h", ".py", ".json", ".toml"}
        ]
        declared = package.get("license_file")
        if declared and (source / declared).is_file():
            files = sorted(set(files) | {source / declared})
        if override.is_file():
            files.append(override)
        if not files:
            raise ValueError(
                f"{name} has no notice text. Add an upstream notice with its exact "
                "source URL under licenses/upstream/ before rebuilding."
            )
        index.extend(
            [
                f"Package: {name}",
                f"Declared license: {package['license']}",
                f"Repository: {package.get('repository') or '(not declared)'}",
            ]
        )
        for path in files:
            text = path.read_text(encoding="utf-8").strip() + "\n"
            digest = hashlib.sha256(text.encode()).hexdigest()
            notices[digest] = text
            relative = (
                path.relative_to(root) if path == override else path.relative_to(source)
            )
            index.append(f"Notice: {relative.as_posix()} -> {digest}")
        index.append("")
    for digest, text in sorted(notices.items()):
        index.extend([f"===== Notice SHA-256: {digest} =====", "", text])
    return "\n".join(index)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail if bundled notices are stale"
    )
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    target = root / "licenses/RUST-DEPENDENCIES.txt"
    text = collect(root)
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            raise SystemExit(
                "Dependency notices are stale; run scripts/collect_licenses.py."
            )
    else:
        target.write_text(text, encoding="utf-8")
    print(f"Dependency notices {'checked' if args.check else 'written'}: {target.name}")


if __name__ == "__main__":
    main()
